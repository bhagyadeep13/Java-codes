package Bit_manipulation;
import java.util.*;
public class left_right_shift 
{
    public static void main(String[] args) 
    {
        // left shift
        System.out.println(91<<2); // left me se 2 bits hata do or two zero right me add kar do

        // right shift
        System.out.println(91>>2); // right me se 2 bits hata do or two zero left me add kar do

    }
}
